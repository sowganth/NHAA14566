export function normalizeLanguage(lang) {
  if (!lang) return 'English';
  const l = String(lang).toLowerCase();
  if (l === 'en' || l === 'english') return 'English';
  if (l === 'ta' || l === 'tamil') return 'Tamil';
  if (l === 'hi' || l === 'hindi') return 'Hindi';
  if (l === 'te' || l === 'telugu') return 'Telugu';
  if (l === 'kn' || l === 'kannada') return 'Kannada';
  if (l === 'ml' || l === 'malayalam') return 'Malayalam';
  if (l === 'mr' || l === 'marathi') return 'Marathi';
  if (l === 'bn' || l === 'bengali') return 'Bengali';
  if (l === 'gu' || l === 'gujarati') return 'Gujarati';
  if (l === 'pa' || l === 'punjabi') return 'Punjabi';
  if (l === 'ur' || l === 'urdu') return 'Urdu';
  return lang.charAt(0).toUpperCase() + lang.slice(1);
}

export function t(key, lang = 'English') {
  const normLang = normalizeLanguage(lang);
  const langDict = UI_TRANSLATIONS[normLang] || UI_TRANSLATIONS.English;
  return langDict[key] || UI_TRANSLATIONS.English[key] || key;
}

